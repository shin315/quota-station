// Keeps every source file of the repository at 1000 lines or fewer.
//
//     node scripts/check-file-length.mjs [--root DIR]
//     npm run check:file-length
//
// Reads the files git tracks under DIR (default: the repository's root), picks
// the code files by extension, and fails when:
//
//   - a file that is not on `.file-length-allowlist` has more than 1000 lines;
//   - a file on the list has more lines than the number written beside it;
//   - a file on the list is down to 1000 lines or fewer, was deleted or
//     renamed, or is no longer one of the files this check reads: its line
//     comes off the list, so that the list never goes stale.
//
// The list holds the files that were over the limit when the check was added:
// "<lines> <path>" per line, `#` starts a comment. A number on it only ever
// goes down. A file over the limit is split into smaller modules; the number
// is never raised and a new file is never added to the list.
//
// Node's standard library only, no install step.

import { execFileSync } from 'node:child_process';
import { readFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const LIMIT = 1000;
const ALLOWLIST = '.file-length-allowlist';

// The files that are read: the languages this repository writes its code in,
// tests and scripts included. Everything else git tracks is left alone: the
// lockfiles (Cargo.lock, package-lock.json), the data (json, jsonl, txt, svg,
// plist, toml, yml and the other configuration), the fixtures that are not
// code, the images, the fonts and the documents (md).
const CODE_EXTENSIONS = ['.rs', '.ts', '.tsx', '.js', '.mjs', '.cjs', '.sh', '.py', '.css'];

// Files with a code extension that nobody on the team writes by hand, one
// reason a line. A prefix ends in `/`, a suffix starts with `.`. Never add a
// file of ours here to get under the limit: split it.
const EXCLUDED = [
  { prefix: 'vendor/', why: 'third-party code copied into the repository' },
  { prefix: 'third_party/', why: 'third-party code copied into the repository' },
  { prefix: 'src-tauri/gen/', why: "generated by Tauri's build (also ignored by git)" },
  { suffix: '.min.js', why: 'minified, generated bundles' },
];

const ADVICE = `Split the file into smaller modules; do not raise the number in ${ALLOWLIST}.`;

const root = rootFromArgs(process.argv.slice(2));
const failures = [];
const notes = [];

const allowed = readAllowlist();
const lines = measureTrackedCode();

for (const [path, count] of lines) {
  const recorded = allowed.get(path);
  if (count > LIMIT && recorded === undefined) {
    failures.push(`${path}: ${count} lines, the limit is ${LIMIT}, and the file is not on ${ALLOWLIST}. ${ADVICE}`);
  } else if (recorded !== undefined && count > recorded) {
    failures.push(`${path}: ${count} lines, ${ALLOWLIST} records ${recorded} (the limit is ${LIMIT}). ${ADVICE}`);
  } else if (recorded !== undefined && count > LIMIT && count < recorded) {
    notes.push(`${path}: ${count} lines now, ${ALLOWLIST} records ${recorded}; write ${count} there so the file cannot grow back.`);
  }
}

for (const [path, recorded] of allowed) {
  const count = lines.get(path);
  if (count === undefined) {
    failures.push(
      `${path}: on ${ALLOWLIST} (${recorded} lines) but it is deleted, renamed, or not a code file this check reads. Remove its line from ${ALLOWLIST}.`,
    );
  } else if (count <= LIMIT) {
    failures.push(`${path}: ${count} lines, within the limit of ${LIMIT}, but still on ${ALLOWLIST} (${recorded} lines). Remove its line from ${ALLOWLIST}.`);
  }
}

for (const note of notes) console.log(`note: ${note}`);

if (failures.length > 0) {
  console.error(`File length check failed (limit ${LIMIT} lines per code file):\n`);
  for (const failure of failures) console.error(`  ${failure}`);
  console.error(`\n${failures.length} problem${failures.length === 1 ? '' : 's'}. ${ADVICE}`);
  process.exit(1);
}
console.log(`File length: ${lines.size} code files checked, none over ${LIMIT} lines except the ${allowed.size} on ${ALLOWLIST}.`);

function rootFromArgs(args) {
  const here = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  if (args.length === 0) return here;
  if (args.length === 2 && args[0] === '--root') return resolve(args[1]);
  console.error('usage: node scripts/check-file-length.mjs [--root DIR]');
  process.exit(2);
}

/** The code files git tracks, each with its number of lines. */
function measureTrackedCode() {
  const tracked = execFileSync('git', ['-C', root, 'ls-files', '-z'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
    .split('\0')
    .filter(Boolean);
  const measured = new Map();
  for (const path of tracked) {
    if (!isChecked(path)) continue;
    let content;
    try {
      if (!statSync(join(root, path)).isFile()) continue; // a submodule
      content = readFileSync(join(root, path));
    } catch {
      continue; // tracked, but deleted from the working tree
    }
    measured.set(path, countLines(content));
  }
  return measured;
}

function isChecked(path) {
  if (!CODE_EXTENSIONS.some((extension) => path.endsWith(extension))) return false;
  return !EXCLUDED.some((rule) => (rule.prefix ? path.startsWith(rule.prefix) : path.endsWith(rule.suffix)));
}

/** As `wc -l`, plus a last line that has no newline after it. */
function countLines(content) {
  if (content.length === 0) return 0;
  let count = 0;
  for (const byte of content) if (byte === 10) count++;
  return content[content.length - 1] === 10 ? count : count + 1;
}

function readAllowlist() {
  const entries = new Map();
  let text;
  try {
    text = readFileSync(join(root, ALLOWLIST), 'utf8');
  } catch {
    failures.push(`${ALLOWLIST} is missing. It lists, one "<lines> <path>" per line, the files that were over ${LIMIT} lines when the check was added.`);
    return entries;
  }
  text.split('\n').forEach((raw, index) => {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) return;
    const match = /^(\d+)\s+(\S.*)$/.exec(line);
    if (!match) {
      failures.push(`${ALLOWLIST}:${index + 1}: "${line}" is not "<lines> <path>".`);
    } else if (entries.has(match[2])) {
      failures.push(`${ALLOWLIST}:${index + 1}: ${match[2]} is listed twice.`);
    } else {
      entries.set(match[2], Number(match[1]));
    }
  });
  return entries;
}
